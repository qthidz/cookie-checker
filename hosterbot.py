    if message.text and (
        message.text.strip().startswith('/') or
        message.text.strip() in KNOWN_BUTTON_TEXTS
    ):
        users_pending_folder.pop(user_id, None)
        users_awaiting_upload.discard(user_id)
        text = message.text.strip().lower()
        # Handle /cancel explicitly with feedback
        if text == '/cancel':
            bot.reply_to(message, "❌ Upload cancel ho gaya.\n\n👇 Niche se koi button press karo.", reply_markup=create_reply_keyboard_main_menu(user_id))
            return
        text = message.text.strip()
        # Re-route to the correct handler for button presses
        logic_func = BUTTON_TEXT_TO_LOGIC.get(text)
        if logic_func:
            logic_func(message)
        elif text.startswith('/start'):
            _logic_send_welcome(message)
        return

    if not message.text:
        msg = bot.reply_to(message, "⚠️ Sirf text mein folder name do. Dobara try karo ya /cancel karo.")
        bot.register_next_step_handler(msg, _process_folder_name_step)
        return
    folder_name = message.text.strip()
