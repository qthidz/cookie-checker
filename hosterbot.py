def auto_install_imports_from_py(file_path, message):
    """Scan a .py file for all top-level imports and pip install any missing packages."""
    try:
        with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
            source = f.read()
    except Exception as e:
        logger.warning(f"Could not read file for import scan: {e}")
        return

    import_lines = re.findall(
        r'^\s*(?:import|from)\s+([\w]+)',
        source, re.MULTILINE
    )
    packages_to_try = set()
    for pkg in import_lines:
        top = pkg.split('.')[0].lower()
        if top and top not in STDLIB_MODULES and len(top) > 1:
            packages_to_try.add(top)

    if not packages_to_try:
        return

    # Check which ones are already importable
    missing = []
    for pkg in packages_to_try:
        try:
            __import__(pkg)
        except ImportError:
            missing.append(pkg)

    if not missing:
        return

    bot.reply_to(
        message,
        f"🔍 File mein yeh packages mile jo install nahi hain:\n`{'`, `'.join(missing)}`\n\n🔄 Installing...",
        parse_mode='Markdown'
    )

    installed = []
    failed = []
    for pkg in missing:
        mapped = TELEGRAM_MODULES.get(pkg, pkg)
        if mapped is None:
            continue
        cmd = [sys.executable, '-m', 'pip', 'install', '--break-system-packages', '--quiet', mapped]
        result = subprocess.run(cmd, capture_output=True, text=True, check=False, encoding='utf-8', errors='ignore')
        if result.returncode == 0:
            installed.append(mapped)
            logger.info(f"Auto-installed: {mapped}")
        else:
            failed.append(mapped)
            logger.warning(f"Auto-install failed for {mapped}: {result.stderr[:200]}")

    lines = []
    if installed:
        lines.append(f"✅ Installed: `{'`, `'.join(installed)}`")
    if failed:
        lines.append(f"⚠️ Install nahi hua (skip): `{'`, `'.join(failed)}`")
    if lines:
        bot.reply_to(message, '\n'.join(lines), parse_mode='Markdown')


